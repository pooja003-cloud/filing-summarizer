"""Reproduce every result in the README with one command.

Clears previously generated outputs, runs the tests, makes 3 LLM runs per
company, checks every run, and runs the planted-error test. Everything lands in
one fresh outputs/run_output.txt.

    python run_all.py              # HPQ and DELL, 3 runs each (6 LLM calls)
    python run_all.py --pause 30   # wait 30s between LLM calls (Pro usage limits)
"""

import argparse
import datetime as dt
import platform
import subprocess
import sys
import time
from pathlib import Path

import bs4
import requests

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "outputs"
TICKERS = ("HPQ", "DELL")
RUNS = (1, 2, 3)
# Generated by earlier runs. section_* and filing_* are regenerated, so kept.
STALE = ("summary_*", "raw_reply_*", "llm_envelope_*", "check_*", "planted_*", "run_output.txt")


def run(args: list[str]) -> int:
    return subprocess.run([sys.executable, *args], cwd=ROOT).returncode


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pause", type=int, default=0, help="seconds between LLM calls")
    pause = ap.parse_args().pause

    OUT.mkdir(exist_ok=True)
    removed = 0
    for pattern in STALE:
        for f in OUT.glob(pattern):
            f.unlink()
            removed += 1

    tests = subprocess.run([sys.executable, "-m", "unittest", "discover", "-s", "tests"],
                           cwd=ROOT, capture_output=True, text=True)
    test_line = (tests.stderr.strip().splitlines() or ["?"])[-1]
    header = [
        f"##### run_all.py - {dt.datetime.now().astimezone():%Y-%m-%d %H:%M %Z}",
        f"Python {platform.python_version()}, requests {requests.__version__}, "
        f"beautifulsoup4 {bs4.__version__}",
        f"Removed {removed} generated files from earlier runs.",
        f"Unit tests: {test_line}",
        "",
    ]
    (OUT / "run_output.txt").write_text("\n".join(header) + "\n", encoding="utf-8")
    print("\n".join(header))
    if tests.returncode != 0:
        sys.exit("Unit tests failed; fix them before spending LLM calls.\n" + tests.stderr)

    first = True
    for t in TICKERS:
        for r in RUNS:
            if pause and not first:
                time.sleep(pause)
            first = False
            if run(["summarize.py", t, "--run", str(r)]) != 0:
                sys.exit(f"summarize.py {t} run {r} failed; see the output above.")

    for t in TICKERS:
        for r in RUNS:
            run(["check.py", t, "--run", str(r)])  # exit 1 just means a check failed
        run(["check.py", t, "--plant"])

    print("\nDone. Full log: outputs/run_output.txt")


if __name__ == "__main__":
    main()
